export function normalizeOnboardingTopic(value: string): string {
  const input = value.trim().toLowerCase();
  const special: Record<string, string> = { 'c++': 'cpp', 'c#': 'c-sharp', 'f#': 'f-sharp' };
  return special[input] ?? input.replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '').replace(/-{2,}/g, '-').slice(0, 50).replace(/-+$/g, '');
}
